'use strict';

// Vendors the JIZURA engine into Mineradio as a single file, built the way upstream's
// build.py builds it:
//   sources = sorted(glob.glob('src/*.js'))
//   js      = '\n'.join(open(f, encoding='utf-8').read() for f in sources)
// Python decodes with universal newlines by default, so upstream's own output has CRLF
// folded to LF and this generator must fold it too or the bytes differ from what upstream
// ships. Exclusions are explicit and justified per file; anything not listed is kept.
//
// Re-run this after an upstream refresh, then let the gate compare the manifest it writes.
// Usage: node scripts/vendor-jizura-engine.js [upstreamRoot]

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');

const EXCLUDED = {
  '12_ui.js': 'editor UI only: defines J.ui/J.uiApi, referenced by none of the other files',
};

const upstreamRoot = process.argv[2] || process.env.JIZURA_ROOT || 'G:\\SoftwareFile\\JIZURA';
const srcDir = path.join(upstreamRoot, 'src');
const outDir = path.join(__dirname, '..', 'vendor', 'jizura');
const bundleFile = path.join(outDir, 'jizura-engine.js');
const licenseFile = path.join(outDir, 'LICENSE.txt');
const manifestFile = path.join(outDir, 'engine-manifest.json');

const sha1 = (buf) => crypto.createHash('sha1').update(buf).digest('hex');

function readUpstreamRevision() {
  try {
    return execFileSync('git', ['-C', upstreamRoot, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
  } catch (error) {
    return null;
  }
}

function main() {
  if (!fs.existsSync(srcDir)) {
    console.error('[FAIL] upstream src/ not found: ' + srcDir);
    process.exit(2);
  }
  const all = fs.readdirSync(srcDir).filter((f) => f.endsWith('.js')).sort();
  const kept = all.filter((f) => !Object.prototype.hasOwnProperty.call(EXCLUDED, f));
  const missingExcluded = Object.keys(EXCLUDED).filter((f) => !all.includes(f));
  if (missingExcluded.length) {
    console.error('[FAIL] excluded files no longer exist upstream (refresh this list): ' + missingExcluded.join(', '));
    process.exit(3);
  }

  const files = [];
  const parts = [];
  for (const name of kept) {
    const raw = fs.readFileSync(path.join(srcDir, name));
    // Mirror python's universal-newline decode: CRLF -> LF, bare CR -> LF.
    const text = raw.toString('utf8').replace(/\r\n?/g, '\n');
    if (!text.trim()) {
      console.error('[FAIL] kept source is empty, which would silently drop a module: ' + name);
      process.exit(4);
    }
    files.push({ file: name, rawBytes: raw.length, rawSha1: sha1(raw), decodedBytes: Buffer.byteLength(text, 'utf8') });
    parts.push(text);
  }
  const bundle = parts.join('\n');

  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(bundleFile, bundle, 'utf8');

  const licenseSrc = path.join(upstreamRoot, 'LICENSE');
  const licenseRaw = fs.readFileSync(licenseSrc);
  fs.writeFileSync(licenseFile, licenseRaw);

  const manifest = {
    note: 'Generated by scripts/vendor-jizura-engine.js. Regenerate after an upstream refresh; quick-check.js pins these values.',
    upstreamRoot,
    upstreamRevision: readUpstreamRevision(),
    upstreamVersion: fs.existsSync(path.join(upstreamRoot, 'VERSION')) ? fs.readFileSync(path.join(upstreamRoot, 'VERSION'), 'utf8').trim() : null,
    generation: "sorted(glob('src/*.js')) minus exclusions, each file decoded as UTF-8 with CRLF folded to LF, joined with a single '\\n' — same steps as upstream build.py:11-12",
    excluded: Object.entries(EXCLUDED).map(([file, why]) => ({ file, why })),
    sourceFileCount: all.length,
    keptFileCount: kept.length,
    files,
    keptFilesRawBytes: files.reduce((a, f) => a + f.rawBytes, 0),
    bundleBytes: Buffer.byteLength(bundle, 'utf8'),
    bundleSha1: sha1(Buffer.from(bundle, 'utf8')),
    licenseBytes: licenseRaw.length,
    licenseSha1: sha1(licenseRaw),
  };
  fs.writeFileSync(manifestFile, JSON.stringify(manifest, null, 2) + '\n', 'utf8');

  console.log('[OK] ' + path.relative(process.cwd(), bundleFile) + '  ' + manifest.bundleBytes + ' B  sha1=' + manifest.bundleSha1);
  console.log('     kept ' + manifest.keptFileCount + '/' + manifest.sourceFileCount + ' files, raw ' + manifest.keptFilesRawBytes + ' B' +
    (manifest.upstreamRevision ? ', upstream ' + manifest.upstreamRevision.slice(0, 12) : ', upstream revision unknown') +
    (manifest.upstreamVersion ? ' v' + manifest.upstreamVersion : ''));
  console.log('     excluded: ' + manifest.excluded.map((e) => e.file).join(', '));
}

main();